void draw_char(t_gui *gui, unsigned char c, t_vec2i pos, unsigned int color)
{
	const unsigned char *glyph;
	t_vec2i d;
	unsigned int *px;

	if (c < 32 || c > 126)
		return ;
	glyph = g_font8[c - 32];
	d.y = 0;
	while (d.y < 8)
	{
		if (pos.y + d.y < 0 || pos.y + d.y >= gui->win.disp_size.y)
		{
			d.y++;
			continue ;
		}
		d.x = 0;
		while (d.x < 8)
		{
			if (((glyph[d.y] >> (7 - d.x)) & 1) != 0)
			{
				if (pos.x + d.x >= 0 && pos.x + d.x < gui->win.disp_size.x)
				{
					px = (unsigned int *)(gui->win.disp_addr
							+ (pos.y + d.y) * gui->win.disp_line_len
							+ (pos.x + d.x) * (gui->win.disp_bpp / 8));
					*px = color;
				}
			}
			d.x++;
		}
		d.y++;
	}
}
