#include "editor.h"

void	reset_capsule(t_scene *sc, t_scene_snap *s)
{
	sc->capsule_count = s->capsule_count;
	ft_memcpy(sc->capsules, s->capsules,
		s->capsule_count * sizeof(t_capsule));
}
