#include "editor.h"

void	reset_cylinder(t_scene *sc, t_scene_snap *s)
{
	sc->cylinder_count = s->cylinder_count;
	ft_memcpy(sc->cylinders, s->cylinders,
		s->cylinder_count * sizeof(t_cylinder));
}
