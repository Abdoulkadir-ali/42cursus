#include "maths.h"

t_mat4	mat4_add(t_mat4 a, t_mat4 b)
{
	t_mat4	res;
	int		i;
	int		j;

	i = 0;
	while (i < 4)
	{
		j = 0;
		while (j < 4)
		{
			res.m[i][j] = a.m[i][j] + b.m[i][j];
			j++;
		}
		i++;
	}
	return (res);
}
