#include "maths.h"

t_mat4	mat4_identity(void)
{
	t_mat4	res;

	ft_memset(&res, 0, sizeof(t_mat4));
	res.m[0][0] = 1.0;
	res.m[1][1] = 1.0;
	res.m[2][2] = 1.0;
	res.m[3][3] = 1.0;
	return (res);
}
