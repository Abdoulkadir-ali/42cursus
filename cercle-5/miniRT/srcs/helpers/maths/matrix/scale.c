#include "maths.h"

t_mat4	mat4_scale_inplace(t_mat4 m, double s)
{
	int	i;
	int	j;

	i = 0;
	while (i < 4)
	{
		j = 0;
		while (j < 4)
		{
			m.m[i][j] *= s;
			j++;
		}
		i++;
	}
	return (m);
}
