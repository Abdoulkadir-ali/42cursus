#include "glb.h"

/**
 * Linearly mixes two 3D vectors (LERP).
 */
void	vec3_mix(float *out, float *a, float *b, float t)
{
	out[0] = a[0] + (b[0] - a[0]) * t;
	out[1] = a[1] + (b[1] - a[1]) * t;
	out[2] = a[2] + (b[2] - a[2]) * t;
}
