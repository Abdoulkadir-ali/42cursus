#include "glb.h"

/**
 * Converts a quaternion (x, y, z, w) to a 4x4 scale/rotation matrix.
 */
t_mat4	quat_to_mat4(t_vec4 q)
{
	t_mat4	m;
	double	v[9];

	m = mat4_identity();
	v[0] = q.x * q.x;
	v[1] = q.y * q.y;
	v[2] = q.z * q.z;
	v[3] = q.x * q.y;
	v[4] = q.x * q.z;
	v[5] = q.y * q.z;
	v[6] = q.w * q.x;
	v[7] = q.w * q.y;
	v[8] = q.w * q.z;
	m.m[0][0] = 1.0 - 2.0 * (v[1] + v[2]);
	m.m[0][1] = 2.0 * (v[3] + v[8]);
	m.m[0][2] = 2.0 * (v[4] - v[7]);
	m.m[1][0] = 2.0 * (v[3] - v[8]);
	m.m[1][1] = 1.0 - 2.0 * (v[0] + v[2]);
	m.m[1][2] = 2.0 * (v[5] + v[6]);
	m.m[2][0] = 2.0 * (v[4] + v[7]);
	m.m[2][1] = 2.0 * (v[5] - v[6]);
	m.m[2][2] = 1.0 - 2.0 * (v[0] + v[1]);
	return (m);
}
