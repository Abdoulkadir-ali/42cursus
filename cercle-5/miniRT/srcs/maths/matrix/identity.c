#include "maths.h"

t_mat4	mat4_identity(void)
{
	t_mat4	res;
	int		i;
	int		j;

	i = 0;
	while (i < 4)
	{
		j = 0;
		while (j < 4)
		{
			res.m[i][j] = 0.0;
			if (i == j)
				res.m[i][j] = 1.0;
			j++;
		}
		i++;
	}
	return (res);
}
