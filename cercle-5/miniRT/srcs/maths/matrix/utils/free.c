#include "maths.h"

void	free_matrix(t_matrix *m)
{
	if (!m)
		return ;
	if (m->dim)
	{
		free(m->dim);
		m->dim = NULL;
	}
	if (m->v)
	{
		free(m->v);
		m->v = NULL;
	}
	free(m);
}