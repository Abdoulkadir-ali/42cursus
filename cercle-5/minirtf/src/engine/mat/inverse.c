#include "skeletal.h"

/* Signed sum of three triple-products — every cofactor entry has this shape.
** S3(s1,a,b,c, s2,d,e,f, s3,g,h,i)
**   = s1*(a*b*c) + s2*(d*e*f) + s3*(g*h*i)   where sN is +1 or -1.   */
#define S3(s1, a, b, c, s2, d, e, f, s3, g, h, i) \
	((s1) * (m[a] * m[b] * m[c]) \
	+ (s2) * (m[d] * m[e] * m[f]) + (s3) * (m[g] * m[h] * m[i]))

static void	inv_rows01(const float m[16], float inv[16])
{
	inv[0] = S3(+1, 5, 10, 15, -1, 5, 11, 14, -1, 9, 6, 15) + S3(+1, 9, 7, 14,
			+1, 13, 6, 11, -1, 13, 7, 10);
	inv[4] = S3(-1, 4, 10, 15, +1, 4, 11, 14, +1, 8, 6, 15) + S3(-1, 8, 7, 14,
			-1, 12, 6, 11, +1, 12, 7, 10);
	inv[8] = S3(+1, 4, 9, 15, -1, 4, 11, 13, -1, 8, 5, 15) + S3(+1, 8, 7, 13,
			+1, 12, 5, 11, -1, 12, 7, 9);
	inv[12] = S3(-1, 4, 9, 14, +1, 4, 10, 13, +1, 8, 5, 14) + S3(-1, 8, 6, 13,
			-1, 12, 5, 10, +1, 12, 6, 9);
	inv[1] = S3(-1, 1, 10, 15, +1, 1, 11, 14, +1, 9, 2, 15) + S3(-1, 9, 3, 14,
			-1, 13, 2, 11, +1, 13, 3, 10);
	inv[5] = S3(+1, 0, 10, 15, -1, 0, 11, 14, -1, 8, 2, 15) + S3(+1, 8, 3, 14,
			+1, 12, 2, 11, -1, 12, 3, 10);
	inv[9] = S3(-1, 0, 9, 15, +1, 0, 11, 13, +1, 8, 1, 15) + S3(-1, 8, 3, 13,
			-1, 12, 1, 11, +1, 12, 3, 9);
	inv[13] = S3(+1, 0, 9, 14, -1, 0, 10, 13, -1, 8, 1, 14) + S3(+1, 8, 2, 13,
			+1, 12, 1, 10, -1, 12, 2, 9);
}

static void	inv_rows23(const float m[16], float inv[16])
{
	inv[2] = S3(+1, 1, 6, 15, -1, 1, 7, 14, -1, 5, 2, 15) + S3(+1, 5, 3, 14, +1,
			13, 2, 7, -1, 13, 3, 6);
	inv[6] = S3(-1, 0, 6, 15, +1, 0, 7, 14, +1, 4, 2, 15) + S3(-1, 4, 3, 14, -1,
			12, 2, 7, +1, 12, 3, 6);
	inv[10] = S3(+1, 0, 5, 15, -1, 0, 7, 13, -1, 4, 1, 15) + S3(+1, 4, 3, 13,
			+1, 12, 1, 7, -1, 12, 3, 5);
	inv[14] = S3(-1, 0, 5, 14, +1, 0, 6, 13, +1, 4, 1, 14) + S3(-1, 4, 2, 13,
			-1, 12, 1, 6, +1, 12, 2, 5);
	inv[3] = S3(-1, 1, 6, 11, +1, 1, 7, 10, +1, 5, 2, 11) + S3(-1, 5, 3, 10, -1,
			9, 2, 7, +1, 9, 3, 6);
	inv[7] = S3(+1, 0, 6, 11, -1, 0, 7, 10, -1, 4, 2, 11) + S3(+1, 4, 3, 10, +1,
			8, 2, 7, -1, 8, 3, 6);
	inv[11] = S3(-1, 0, 5, 11, +1, 0, 7, 9, +1, 4, 1, 11) + S3(-1, 4, 3, 9, -1,
			8, 1, 7, +1, 8, 3, 5);
	inv[15] = S3(+1, 0, 5, 10, -1, 0, 6, 9, -1, 4, 1, 10) + S3(+1, 4, 2, 9, +1,
			8, 1, 6, -1, 8, 2, 5);
}

int	skel_m4_inverse(const t_mat4 m, t_mat4 out)
{
	float	inv[16];
	float	det;
	int		i;

	inv_rows01(m, inv);
	inv_rows23(m, inv);
	det = m[0] * inv[0] + m[1] * inv[4] + m[2] * inv[8] + m[3] * inv[12];
	if (det > -1e-9f && det < 1e-9f)
		return (-1);
	det = 1.0f / det;
	i = -1;
	while (++i < 16)
		out[i] = inv[i] * det;
	return (0);
}
