#include "io.h"

const char	*json_skip_ws(const char *p, const char *end)
{
	if (!p)
		return (end);
	while (p < end && (*p == ' ' || *p == '\t' || *p == '\n' || *p == '\r'))
		p++;
	return (p);
}
