#include "exec.h"

int	ft_env(char **envp)
{
    int	i;

    i = 0;
    while (envp && envp[i])
    {
        if (ft_strchr(envp[i], '='))
            ft_putendl_fd(envp[i], 1);
        i++;
    }
    return (0);
}
