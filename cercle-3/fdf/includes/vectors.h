#ifndef VECTORS_H
# define VECTORS_H

// 2D Vector
typedef struct s_vec2
{
	int	x;
	int	y;
}	t_vec2;

// 2D Vector (double precision)
typedef struct s_vec2d
{
	double	x;
	double	y;
}	t_vec2d;

// 3D Vector
typedef struct s_vec3
{
	int	x;
	int	y;
	int	z;
}	t_vec3;

// 3D Vector (double precision)
typedef struct s_vec3d
{
	double	x;
	double	y;
	double	z;
}	t_vec3d;

#endif
